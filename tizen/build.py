#!/usr/bin/env python3
"""Builds Bobcorn for Samsung TVs (Tizen 3+, 2017 and newer): build/Bobcorn.wgt, the web app in tizen/app plus the
torrent engine in tizen/service, which the TV runs as a Node.js service.

    python3 tizen/build.py                                   # build/Bobcorn.wgt, not signed
    python3 tizen/build.py --sign author.p12 --password-file pw.txt
    python3 tizen/build.py --sign author.p12 --password-file pw.txt --install 192.168.1.50

TVs only install signed packages. --sign uses tizen.js (github.com/reisxd/tizen.js, `npm i -g github:reisxd/tizen.js`,
or set TIZENJS to its cli.js) with a Tizen author certificate and Tizen's public distributor certificate; that is what
2017-2022 TVs take. 2023+ TVs (Tizen 7) need a Samsung certificate instead: build unsigned and install with
TizenBrew Installer, which re-signs it with your Samsung account.
"""
import json
import os
import shutil
import subprocess
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, 'build')
WGT = os.path.join(OUT, 'Bobcorn.wgt')
SKIP = ('/test/', '/dev.js', '.DS_Store', '/node_modules/', 'app/js/keys.js')


def files():
    yield os.path.join(HERE, 'config.xml'), 'config.xml'
    yield os.path.join(HERE, 'icon.png'), 'icon.png'
    for folder in ('app', 'service'):
        base = os.path.join(HERE, folder)
        for dirpath, _, names in os.walk(base):
            for name in sorted(names):
                path = os.path.join(dirpath, name)
                rel = os.path.relpath(path, HERE).replace(os.sep, '/')
                if not any(s in '/' + rel for s in SKIP):
                    yield path, rel


def tizenjs():
    path = os.environ.get('TIZENJS')
    if path:
        return ['node', path]
    found = shutil.which('tizenjs')
    if found:
        return [found]
    sys.exit('Signing needs tizen.js: npm i -g github:reisxd/tizen.js, or set TIZENJS to its cli.js.')


def sign(cert, password, expected):
    # tizen.js treats its input as a package only when the name ends in .wgt; anything else is read as a folder
    # (the current directory), so the unsigned copy must keep the .wgt ending.
    unsigned = os.path.join(OUT, 'Bobcorn-unsigned.wgt')
    os.replace(WGT, unsigned)
    run = subprocess.run(tizenjs() + ['build', unsigned, '-t', 'wgt', '-o', WGT, '--author', cert,
                                      '--authorPwd', password, '-p', 'public'], capture_output=True, text=True,
                         cwd=OUT)
    os.remove(unsigned)
    if run.returncode != 0 or not os.path.exists(WGT):
        sys.exit('Signing failed:\n' + (run.stdout + run.stderr).strip())
    with zipfile.ZipFile(WGT) as z:
        names = set(z.namelist())
    if not {'author-signature.xml', 'signature1.xml'} <= names:
        sys.exit('The package came back without its signatures.')
    # The signed package must hold exactly what was built, nothing more.
    extra = {n for n in names if not n.endswith('/')} - expected - {'author-signature.xml', 'signature1.xml'}
    if extra:
        os.remove(WGT)
        sys.exit('Signing added files that were not built (%s...); package deleted.' % sorted(extra)[0])


def main(args):
    if not os.path.exists(os.path.join(HERE, 'service', 'index.js')):
        sys.exit('tizen/service/index.js is missing.')
    os.makedirs(OUT, exist_ok=True)
    built = set()
    with zipfile.ZipFile(WGT, 'w', zipfile.ZIP_DEFLATED) as z:
        for path, rel in files():
            z.write(path, rel)
            built.add(rel)
        # Optional API keys, so they needn't be typed with the remote: tizen/keys.json (git-ignored), e.g.
        # {"omdb": "…", "opensubtitles": "…"}. Keys typed in Settings on the TV take precedence.
        keys = {}
        keys_file = os.path.join(HERE, 'keys.json')
        if os.path.exists(keys_file):
            with open(keys_file) as f:
                keys = {k: v for k, v in json.load(f).items() if k in ('omdb', 'opensubtitles') and isinstance(v, str) and v.strip()}
        z.writestr('app/js/keys.js', '/* Generated by tizen/build.py. */\nwindow.BOBCORN_KEYS = %s;\n' % json.dumps(keys))
        built.add('app/js/keys.js')
        if keys:
            print('Built in the %s key%s from tizen/keys.json' % (' and '.join(sorted(keys)), 's' if len(keys) > 1 else ''))
    signed = False
    if '--sign' in args:
        cert = args[args.index('--sign') + 1]
        password = os.environ.get('TIZEN_CERT_PASSWORD', '')
        if '--password-file' in args:
            with open(args[args.index('--password-file') + 1]) as f:
                password = f.read().strip()
        sign(os.path.abspath(cert), password, built)
        signed = True
    print('Built %s (%d KB, %s)' % (os.path.relpath(WGT, ROOT), os.path.getsize(WGT) // 1024,
                                    'signed' if signed else 'not signed'))
    if '--install' in args:
        if not signed:
            sys.exit('--install needs --sign: the TV refuses unsigned packages.')
        sys.path.insert(0, os.path.join(HERE, 'tools'))
        import sdb
        host = args[args.index('--install') + 1]
        sdb.install(host, WGT)
        print(sdb.Connection(host).shell('0 was_execute ' + sdb.APP_ID).strip())


if __name__ == '__main__':
    main(sys.argv[1:])
